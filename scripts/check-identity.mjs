/**
 * @typedef {object} Person
 * @property {string | undefined} name
 * @property {string | undefined} email
 * @property {string | undefined} url
 */

/**
 * Parses an npm-style person: `"Name <email> (url)"` or `{ name, email, url }`. Composer's
 * `homepage` is read as `url`.
 * @param {unknown} value
 * @returns {Person | null} Null when the value is neither a string nor an object.
 */
export function parsePerson(value) {
  if (typeof value === "string") {
    const match = /^\s*([^<(]*?)\s*(?:<([^>]*)>)?\s*(?:\(([^)]*)\))?\s*$/.exec(value);
    if (!match) return { name: value.trim(), email: undefined, url: undefined };
    return {
      name: match[1] || undefined,
      email: match[2]?.trim() || undefined,
      url: match[3]?.trim() || undefined,
    };
  }
  if (value && typeof value === "object" && !Array.isArray(value)) {
    const str = (v) => (typeof v === "string" ? v : undefined);
    return {
      name: str(value.name),
      email: str(value.email),
      url: str(value.url ?? value.homepage),
    };
  }
  return null;
}

/** Compares URLs ignoring a trailing slash and the scheme/host case. */
function sameUrl(actual, expected) {
  const normalise = (url) =>
    url
      .trim()
      .replace(/\/+$/, "")
      .replace(/^[a-z]+:\/\/[^/]+/i, (m) => m.toLowerCase());
  return typeof actual === "string" && normalise(actual) === normalise(expected);
}

/**
 * Lists how a person differs from the project author (name, email and GitHub URL are required).
 * @param {Person} person
 * @param {string} urlField Field name used in messages (`url` or `homepage`).
 * @returns {string[]} One message per mismatch; empty when the person is the author.
 */
export function personMismatches(person, urlField = "url") {
  const problems = [];
  const show = (value) => (value === undefined ? "missing" : JSON.stringify(value));
  if (person.name !== IDENTITY.author) {
    problems.push(`name is ${show(person.name)}; expected "${IDENTITY.author}"`);
  }
  if (typeof person.email !== "string" || person.email.toLowerCase() !== IDENTITY.email) {
    problems.push(`email is ${show(person.email)}; expected "${IDENTITY.email}"`);
  }
  if (!sameUrl(person.url, IDENTITY.githubUrl)) {
    problems.push(`${urlField} is ${show(person.url)}; expected "${IDENTITY.githubUrl}"`);
  }
  return problems;
}

/**
 * Normalises a repository reference to `https://github.com/<owner>/<repo>` where possible.
 * Accepts a string or an npm `{ url }` object, `git+https:`, `git:`, `ssh:`, `git@github.com:`,
 * `github:owner/repo` and the bare `owner/repo` shorthand.
 * @param {unknown} value
 * @returns {string | null}
 */
export function normalizeRepositoryUrl(value) {
  const raw =
    typeof value === "string" ? value : value && typeof value === "object" ? value.url : null;
  if (typeof raw !== "string" || raw.trim() === "") return null;
  let url = raw.trim();
  const shorthand = /^(?:github:)?([\w.-]+)\/([\w.-]+)$/.exec(url);
  if (shorthand) url = `https://github.com/${shorthand[1]}/${shorthand[2]}`;
  url = url
    .replace(/^git\+/, "")
    .replace(/^git@github\.com:/i, "https://github.com/")
    .replace(/^(?:git|ssh):\/\/(?:git@)?github\.com\//i, "https://github.com/")
    .replace(/^http:\/\//i, "https://")
    .replace(/\/+$/, "")
    .replace(/\.git$/, "");
  return url.replace(/^https:\/\/github\.com/i, "https://github.com");
}

/**
 * Finds copyright lines (`Copyright (c) 2026 Name`, `Copyright 2025-2026 Name`, `© …`).
 * @param {string} text
 * @returns {{ line: number, holder: string }[]}
 */
export function copyrightHolders(text) {
  const holders = [];
  text.split(/\r?\n/).forEach((line, index) => {
    if (!/^\s*Copyright\s+(?:\([cC]\)|©|\d{4})/.test(line)) return;
    const holder = line
      .replace(/^\s*Copyright\s+/, "")
      .replace(/^(?:\([cC]\)|©)\s*/, "")
      .replace(/^\d{4}(?:\s*[-–,]\s*(?:\d{4}|present))*,?\s*/, "")
      .replace(/[\s.]+$/, "");
    holders.push({ line: index + 1, holder });
  });
  return holders;
}

/**
 * Returns the body of the first Markdown ATX section whose heading text matches `title`
 * (headings inside fenced code blocks are ignored). The body runs to the next heading of the
 * same or a higher level.
 * @param {string} text
 * @param {RegExp} title Matched against the heading text.
 * @returns {{ line: number, body: string } | null}
 */
export function markdownSection(text, title) {
  const lines = text.split(/\r?\n/);
  let fence = null;
  let start = -1;
  let level = 0;
  const body = [];
  for (let index = 0; index < lines.length; index++) {
    const line = lines[index];
    const fenceMatch = /^\s{0,3}(`{3,}|~{3,})/.exec(line);
    if (fenceMatch) {
      if (fence === null) fence = fenceMatch[1][0];
      else if (fenceMatch[1][0] === fence) fence = null;
      if (start !== -1) body.push(line);
      continue;
    }
    const heading = fence === null ? /^\s{0,3}(#{1,6})\s+(.*?)\s*#*\s*$/.exec(line) : null;
    if (start === -1) {
      if (heading && title.test(heading[2])) {
        start = index;
        level = heading[1].length;
      }
      continue;
    }
    if (heading && heading[1].length <= level) break;
    body.push(line);
  }
  return start === -1 ? null : { line: start + 1, body: body.join("\n") };
}

/**
 * Whether CODEOWNERS text assigns the catch-all pattern `*` to `@owner`.
 * @param {string} text
 * @param {string} owner GitHub user without `@`.
 * @returns {boolean}
 */
export function hasCatchAllOwner(text, owner) {
  return text.split(/\r?\n/).some((line) => {
    const content = line.replace(/(^|\s)#.*$/, "").trim();
    if (content === "") return false;
    const [pattern, ...owners] = content.split(/\s+/);
    return pattern === "*" && owners.some((o) => o.toLowerCase() === `@${owner}`.toLowerCase());
  });
}

