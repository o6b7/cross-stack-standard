/**
 * @typedef {object} Context
 * @property {string} root
 * @property {boolean} release
 * @property {import("./lib/versioning.mjs").Finding[]} findings
 * @property {string[]} checked Files that were read.
 */

function report(ctx, id, file, line, message) {
  ctx.findings.push({ id, file, line, message });
}

/** Reads a text file; reports it as missing in release mode when `required`. */
function readText(ctx, rel, required) {
  const abs = resolveRel(ctx.root, rel);
  if (!isFile(abs)) {
    if (required && ctx.release) {
      report(ctx, "IDENTITY-MISSING", rel, 0, "required for a release but not found");
    }
    return null;
  }
  ctx.checked.push(rel);
  return fs.readFileSync(abs, "utf8").replace(/^\uFEFF/, "");
}

/** Reads and parses a JSON file; reports invalid JSON. */
function readJson(ctx, rel, required) {
  const text = readText(ctx, rel, required);
  if (text === null) return null;
  try {
    return { text, value: JSON.parse(text) };
  } catch (error) {
    report(
      ctx,
      "IDENTITY-JSON",
      rel,
      jsonErrorLine(text, error),
      `not valid JSON (${error.message})`,
    );
    return null;
  }
}

/** Checks an author-like field that must be an object (plugin.json, marketplace owner/entry). */
function checkAuthorObject(ctx, rel, text, keys, value) {
  const where = keys.join(".").replace(/\.(\d+)\./g, "[$1].");
  const line = memberLine(text, keys);
  if (value === undefined) {
    report(
      ctx,
      "IDENTITY-AUTHOR",
      rel,
      line,
      `${where} is missing; expected { name, email, url } of ${IDENTITY.author}`,
    );
    return;
  }
  const person =
    value && typeof value === "object" && !Array.isArray(value) ? parsePerson(value) : null;
  if (!person) {
    report(
      ctx,
      "IDENTITY-AUTHOR",
      rel,
      line,
      `${where} must be an object with name, email and url`,
    );
    return;
  }
  for (const problem of personMismatches(person)) {
    report(ctx, "IDENTITY-AUTHOR", rel, line, `${where} ${problem}`);
  }
}

/** Checks `repository` when declared. */
function checkRepository(ctx, rel, text, keys, value) {
  if (value === undefined) return;
  const url = normalizeRepositoryUrl(value);
  if (url !== IDENTITY.repositoryUrl) {
    report(
      ctx,
      "IDENTITY-REPOSITORY",
      rel,
      memberLine(text, keys),
      `${keys.join(".").replace(/\.(\d+)\./g, "[$1].")} points at ${JSON.stringify(url ?? value)}; expected "${IDENTITY.repositoryUrl}"`,
    );
  }
}

function checkPluginManifest(ctx) {
  const rel = IDENTITY_FILES.pluginManifest;
  const json = readJson(ctx, rel, true);
  if (!json || !json.value || typeof json.value !== "object") return;
  const { text, value } = json;
  if (value.name !== IDENTITY.projectName) {
    report(
      ctx,
      "IDENTITY-NAME",
      rel,
      memberLine(text, ["name"]),
      `name is ${JSON.stringify(value.name)}; expected "${IDENTITY.projectName}"`,
    );
  }
  checkAuthorObject(ctx, rel, text, ["author"], value.author);
  checkRepository(ctx, rel, text, ["repository"], value.repository);
}

function checkMarketplace(ctx) {
  const rel = IDENTITY_FILES.marketplace;
  const json = readJson(ctx, rel, true);
  if (!json || !json.value || typeof json.value !== "object") return;
  const { text, value } = json;
  if (value.name !== IDENTITY.projectName) {
    report(
      ctx,
      "IDENTITY-NAME",
      rel,
      memberLine(text, ["name"]),
      `name is ${JSON.stringify(value.name)}; expected "${IDENTITY.projectName}"`,
    );
  }
  checkAuthorObject(ctx, rel, text, ["owner"], value.owner);
  const entries = Array.isArray(value.plugins) ? value.plugins : [];
  const index = entries.findIndex((entry) => entry && entry.name === IDENTITY.projectName);
  if (index === -1) {
    report(
      ctx,
      "IDENTITY-NAME",
      rel,
      memberLine(text, ["plugins"]),
      `plugins has no entry named "${IDENTITY.projectName}"`,
    );
    return;
  }
  const entry = entries[index];
  // Entry display fields override plugin.json, so they must match when present.
  if (entry.author !== undefined) {
    checkAuthorObject(ctx, rel, text, ["plugins", String(index), "author"], entry.author);
  }
  checkRepository(ctx, rel, text, ["plugins", String(index), "repository"], entry.repository);
}

function checkPackageJson(ctx, rel, required, scoped) {
  const json = readJson(ctx, rel, required);
  if (!json || !json.value || typeof json.value !== "object") return;
  const { text, value } = json;
  const line = memberLine(text, ["author"]);
  if (value.author === undefined) {
    report(
      ctx,
      "IDENTITY-AUTHOR",
      rel,
      line,
      `author is missing; expected "${IDENTITY.author} <${IDENTITY.email}> (${IDENTITY.githubUrl})"`,
    );
  } else {
    const person = parsePerson(value.author);
    if (!person) report(ctx, "IDENTITY-AUTHOR", rel, line, "author must be a string or an object");
    else
      for (const problem of personMismatches(person))
        report(ctx, "IDENTITY-AUTHOR", rel, line, `author ${problem}`);
  }
  if (scoped && (typeof value.name !== "string" || !value.name.startsWith(IDENTITY.npmScope))) {
    report(
      ctx,
      "IDENTITY-NAME",
      rel,
      memberLine(text, ["name"]),
      `name is ${JSON.stringify(value.name)}; expected the ${IDENTITY.npmScope}* scope`,
    );
  }
  checkRepository(ctx, rel, text, ["repository"], value.repository);
}

function checkComposerJson(ctx, rel) {
  const json = readJson(ctx, rel, false);
  if (!json || !json.value || typeof json.value !== "object") return;
  const { text, value } = json;
  if (typeof value.name !== "string" || !value.name.startsWith(IDENTITY.composerVendor)) {
    report(
      ctx,
      "IDENTITY-NAME",
      rel,
      memberLine(text, ["name"]),
      `name is ${JSON.stringify(value.name)}; expected the ${IDENTITY.composerVendor}* vendor`,
    );
  }
  const line = memberLine(text, ["authors"]);
  const authors = Array.isArray(value.authors) ? value.authors : [];
  const index = authors.findIndex((author) => author && author.name === IDENTITY.author);
  if (index === -1) {
    report(
      ctx,
      "IDENTITY-AUTHOR",
      rel,
      line,
      `authors does not list "${IDENTITY.author}" (with email and homepage)`,
    );
    return;
  }
  const person = parsePerson(authors[index]);
  for (const problem of personMismatches(person, "homepage")) {
    report(
      ctx,
      "IDENTITY-AUTHOR",
      rel,
      memberLine(text, ["authors", String(index)]),
      `authors[${index}] ${problem}`,
    );
  }
}

function checkLicense(ctx, rel, required) {
  const text = readText(ctx, rel, required);
  if (text !== null) checkLicenseText(ctx, rel, text);
}

function checkLicenseText(ctx, rel, text) {
  const holders = copyrightHolders(text);
  if (holders.length === 0) {
    report(
      ctx,
      "IDENTITY-LICENSE",
      rel,
      0,
      `no copyright line; expected "Copyright (c) <year> ${IDENTITY.author}"`,
    );
    return;
  }
  for (const { line, holder } of holders) {
    if (holder !== IDENTITY.author) {
      report(
        ctx,
        "IDENTITY-LICENSE",
        rel,
        line,
        `copyright holder is ${JSON.stringify(holder)}; expected "${IDENTITY.author}"`,
      );
    }
  }
}

/**
 * A distributable copy of LICENSE must match the root notice (line endings aside). Without a
 * root LICENSE the copy's own copyright line is checked.
 * @param {Context} ctx
 * @param {string} rel
 * @param {string} generator
 */
function checkCopiedLicense(ctx, rel, generator) {
  const copy = readText(ctx, rel, true);
  if (copy === null) return;
  const rootAbs = resolveRel(ctx.root, IDENTITY_FILES.license);
  if (!isFile(rootAbs)) {
    checkLicenseText(ctx, rel, copy);
    return;
  }
  const lf = (text) => text.replace(/^\uFEFF/, "").replace(/\r\n/g, "\n");
  if (lf(fs.readFileSync(rootAbs, "utf8")) !== lf(copy)) {
    report(
      ctx,
      "IDENTITY-LICENSE",
      rel,
      0,
      `differs from ${IDENTITY_FILES.license}; run ${generator}`,
    );
  }
}

/** The plugin license travels in every installed plugin copy. */
function checkPluginLicense(ctx) {
  checkCopiedLicense(ctx, IDENTITY_FILES.pluginLicense, "node scripts/build-plugin-data.mjs");
}

/** The portable skill is installed by copying its directory, so its license travels with it. */
function checkAgentSkillLicense(ctx) {
  checkCopiedLicense(ctx, IDENTITY_FILES.agentSkillLicense, "node scripts/build-agent-skill.mjs");
}

/**
 * Kit template files are copied into adopters' repositories one by one, without the LICENSE file,
 * so each file whose header names `cross-stack-standard vX.Y.Z` must carry the MIT notice in that
 * header: an SPDX line and a copyright line naming the author. Vendored gate packages are
 * skipped: they carry their package's LICENSE (required in release mode).
 */
function checkKitNotices(ctx) {
  const skipDirs = new Set([".git", "node_modules", "vendor"]);
  for (const rel of walkFiles(ctx.root, PATHS.templates, { skipDirs })) {
    let text;
    try {
      text = readTextFile(resolveRel(ctx.root, rel));
    } catch {
      continue;
    }
    if (text === null) continue;
    const header = text.split(/\r?\n/).slice(0, HEADER_MAX_LINES);
    HEADER_RE.lastIndex = 0;
    if (!HEADER_RE.test(header.join("\n"))) continue;
    ctx.checked.push(rel);
    const bare = header.map((line) => line.replace(/^\s*(?:\/\/+|#+|\*+|\/\*+|<!--|--|;+)\s?/, ""));
    if (!bare.some((line) => line.trim() === KIT_SPDX_LINE)) {
      report(ctx, "IDENTITY-NOTICE", rel, 1, `header has no "${KIT_SPDX_LINE}" line`);
    }
    const holders = copyrightHolders(bare.join("\n"));
    if (!holders.some(({ holder }) => holder === IDENTITY.author)) {
      report(
        ctx,
        "IDENTITY-NOTICE",
        rel,
        1,
        `header has no "Copyright (c) <year> ${IDENTITY.author}" line`,
      );
    }
  }
}

function checkReadme(ctx) {
  const rel = IDENTITY_FILES.readme;
  const text = readText(ctx, rel, true);
  if (text === null) return;
  const section = markdownSection(text, /^authors?$/i);
  if (!section) {
    report(ctx, "IDENTITY-README", rel, 0, 'no "Author" section (name, GitHub, LinkedIn, email)');
    return;
  }
  const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const required = [
    ["the author name", new RegExp(escape(IDENTITY.author))],
    ["the GitHub profile link", new RegExp(`${escape(IDENTITY.githubUrl)}/?(?![\\w./-]*[\\w-])`)],
    [
      "the LinkedIn link",
      new RegExp(`${escape(IDENTITY.linkedinUrl.replace(/\/$/, ""))}/?(?![\\w-])`),
    ],
    ["the email address", new RegExp(escape(IDENTITY.email), "i")],
  ];
  for (const [label, pattern] of required) {
    if (!pattern.test(section.body)) {
      report(ctx, "IDENTITY-README", rel, section.line, `Author section is missing ${label}`);
    }
  }
}

function checkContact(ctx, rel) {
  const text = readText(ctx, rel, true);
  if (text === null) return;
  if (!text.toLowerCase().includes(IDENTITY.email)) {
    report(ctx, "IDENTITY-CONTACT", rel, 0, `does not give the contact email ${IDENTITY.email}`);
  }
}

function checkCodeowners(ctx) {
  const rel = IDENTITY_FILES.codeowners;
  const text = readText(ctx, rel, true);
  if (text === null) return;
  if (!hasCatchAllOwner(text, IDENTITY.githubUser)) {
    report(ctx, "IDENTITY-CODEOWNERS", rel, 0, `no catch-all line "* @${IDENTITY.githubUser}"`);
  }
}

/**
 * Runs every identity check.
 * @param {string} root Repository root.
 * @param {{ release?: boolean }} [options] `release` requires every identity file to exist.
 * @returns {{ ok: boolean, release: boolean, checked: string[], findings: import("./lib/versioning.mjs").Finding[] }}
 */
export function checkIdentity(root, options = {}) {
  /** @type {Context} */
  const ctx = { root, release: Boolean(options.release), findings: [], checked: [] };

  checkPluginManifest(ctx);
  checkMarketplace(ctx);
  checkPackageJson(ctx, IDENTITY_FILES.rootPackage, true, false);
  checkComposerJson(ctx, PATHS.rootComposer);
  checkLicense(ctx, IDENTITY_FILES.license, true);
  checkPluginLicense(ctx);
  checkAgentSkillLicense(ctx);

  const packageDirs = listDirectories(root, PATHS.packages);
  for (const name of packageDirs) {
    const dir = `${PATHS.packages}/${name}`;
    const hasPackage = isFile(resolveRel(root, `${dir}/package.json`));
    const hasComposer = isFile(resolveRel(root, `${dir}/composer.json`));
    if (hasPackage) checkPackageJson(ctx, `${dir}/package.json`, false, true);
    if (hasComposer) {
      checkComposerJson(ctx, `${dir}/composer.json`);
    }
    if (!hasPackage && !hasComposer && ctx.release) {
      report(ctx, "IDENTITY-MISSING", dir, 0, "has no package.json or composer.json");
    }
    checkLicense(ctx, `${dir}/LICENSE`, true);
  }
  checkKitNotices(ctx);
  checkReadme(ctx);
  checkContact(ctx, IDENTITY_FILES.security);
  checkContact(ctx, IDENTITY_FILES.codeOfConduct);
  checkCodeowners(ctx);

  return {
    ok: ctx.findings.length === 0,
    release: ctx.release,
    checked: ctx.checked,
    findings: ctx.findings,
  };
}

/**
 * Runs the identity check.
 * @param {string[]} argv Arguments after the script name.
 * @param {{ stdout: { write(chunk: string): unknown }, stderr: { write(chunk: string): unknown } }} [io]
 * @returns {number} Exit code.
 */
export function main(argv, io = process) {
  let options;
  try {
    options = parseCli(argv, { release: { type: "boolean" } });
  } catch (error) {
    if (!(error instanceof UsageError)) throw error;
    io.stderr.write(`check-identity: ${error.message}\n\n${USAGE}\n`);
    return 2;
  }
  if (options.help) {
    io.stdout.write(`${USAGE}\n`);
    return 0;
  }
  const result = checkIdentity(options.root, { release: Boolean(options.release) });
  if (options.json) {
    io.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  } else {
    for (const finding of result.findings) io.stdout.write(`${formatFinding(finding)}\n`);
    const mode = result.release ? " (release mode)" : "";
    io.stdout.write(
      `check-identity: ${result.checked.length} file(s) checked, ${result.findings.length} finding(s)${mode}\n`,
    );
  }
  return result.ok ? 0 : 1;
}

if (isMainModule(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`check-identity: internal error: ${error.stack ?? error}\n`);
    process.exitCode = 2;
  }
}
