describe("released template hashes are frozen", () => {
  const released = (t) => {
    const root = scratchRepo(t);
    buildPluginData({ root, vendored: [] });
    write(
      at(root, "CHANGELOG.md"),
      `# Changelog\n\n## [Unreleased]\n\n## [${VERSION}] - 2026-10-01\n\n### Added\n\n- First.\n`,
    );
    return root;
  };

  test("a template change after the release cannot rewrite that version's manifest", (t) => {
    const root = released(t);
    const file = `${DATA}/template-hashes/${VERSION}.json`;
    const before = read(root, file);
    write(
      at(root, `${TEMPLATES}/shared/cross-stack/bin/cross-stack.mjs`),
      `${read(root, PATHS.bin)}\n// later\n`,
    );
    for (const check of [false, true]) {
      const result = buildPluginData({ root, check, vendored: [] });
      assert.equal(result.ok, false);
      assert.deepEqual(findingKeys(result), [`released-hashes ${file}`]);
      assert.match(
        result.findings[0].message,
        new RegExp(
          `set VERSION to the next pre-release \\(for example ${nextPrerelease(VERSION).replaceAll(".", "\\.")}\\)`,
        ),
      );
    }
    assert.equal(read(root, file), before, "nothing was written");
    const refrozen = buildPluginData({ root, refreeze: true, vendored: [] });
    assert.equal(refrozen.ok, true, "--refreeze allows it on the release branch");
    assert.notEqual(read(root, file), before);
  });

  test("an unreleased version, or an unchanged manifest, builds as usual", (t) => {
    const root = scratchRepo(t);
    buildPluginData({ root, vendored: [] });
    write(at(root, "CHANGELOG.md"), "# Changelog\n\n## [Unreleased]\n\n- Pending.\n");
    write(at(root, `${TEMPLATES}/web/.prettierrc.json`), "{}\n");
    assert.equal(buildPluginData({ root, vendored: [] }).ok, true);
    const frozenButEqual = released(t);
    assert.equal(buildPluginData({ root: frozenButEqual, check: true, vendored: [] }).ok, true);
  });

  test("reads release dates from the changelog and suggests the next pre-release", (t) => {
    const root = released(t);
    assert.equal(isReleasedVersion(root, VERSION), true);
    assert.equal(isReleasedVersion(root, "9.9.9"), false);
    assert.equal(nextPrerelease("1.2.3"), "1.2.4-dev.0");
    assert.equal(nextPrerelease("1.2.3-rc.1"), "1.2.4-dev.0");
  });
});

describe("source validation", () => {
  const problems = (root) => {
    const result = buildPluginData({ root, vendored: [] });
    assert.equal(result.ok, false);
    assert.deepEqual(result.written, [], "nothing is written when a source is invalid");
    return result.findings.map((finding) => `${finding.path}:${finding.line} ${finding.message}`);
  };

  test("a missing registry", (t) => {
    const root = scratchRepo(t);
    fs.rmSync(at(root, "registry/rules.json"));
    assert.deepEqual(problems(root), ["registry/rules.json:1 not found"]);
  });

  test("invalid rules, with the line of the offending field", (t) => {
    const root = scratchRepo(t);
    const rules = sampleRules();
    rules[0].track = "desktop";
    rules[1].id = rules[0].id;
    rules.push({
      ...sampleRules()[0],
      id: "WEB-003",
      profiles: ["remix"],
      gate: { kind: "eslint" },
    });
    write(at(root, "registry/rules.json"), { version: 1, rules });
    assert.deepEqual(problems(root), [
      'registry/rules.json:7 "track" must be one of laravel, web, mobile, client, shared',
      "registry/rules.json:24 duplicate rule id WEB-002",
      'registry/rules.json:49 "gate" must be null or an object with "kind" and "id"',
      'registry/rules.json:57 "profiles" must be absent or a list of next, react-spa',
    ]);
  });

  test("a registry that is neither a list nor an object with rules", (t) => {
    const root = scratchRepo(t);
    write(at(root, "registry/rules.json"), { rules: {} });
    assert.deepEqual(problems(root), [
      'registry/rules.json:1 must be an array of rules or an object with a "rules" array',
    ]);
  });

  test("invalid JSON and duplicate keys", (t) => {
    const root = scratchRepo(t);
    write(at(root, "registry/rules.json"), '{\n  "rules": [\n}\n');
    write(at(root, "schemas/protected-paths.json"), '{\n  "paths": [],\n  "paths": []\n}\n');
    const found = problems(root);
    assert.equal(found.length, 2);
    assert.match(found[0], /^schemas\/protected-paths\.json:3 duplicate key at \/paths$/);
    assert.match(found[1], /^registry\/rules\.json:3 invalid JSON: /);
  });

  test("a schema whose $id names another version", (t) => {
    const root = scratchRepo(t, { version: "1.2.3" });
    write(at(root, "VERSION"), "1.2.4\n");
    const found = problems(root);
    assert.equal(found.length, 2);
    assert.match(
      found[0],
      /^schemas\/standard\.schema\.json:3 "\$id" must be .*\/v1\.2\.4\/.*stamp-version/,
    );
    assert.match(found[1], /^schemas\/allowlist\.schema\.json:3 "\$id" must be /);
  });

  test("a schema keyword the kit's validator cannot run", (t) => {
    const root = scratchRepo(t);
    const schema = readJson(at(root, "schemas/allowlist.schema.json"));
    schema.properties.rule.maxLength = 8;
    write(at(root, "schemas/allowlist.schema.json"), schema);
    assert.deepEqual(problems(root), [
      'schemas/allowlist.schema.json:1 #/properties/rule: unsupported JSON Schema keyword "maxLength" (the kit\'s validator in cross-stack.mjs must support it first)',
    ]);
  });

  test("an invalid VERSION", (t) => {
    const root = scratchRepo(t);
    write(at(root, "VERSION"), "1.0\n");
    assert.deepEqual(problems(root), ['VERSION:1 "1.0" is not a SemVer version']);
  });

  test("a kit tool without its generated block", (t) => {
    const root = scratchRepo(t);
    write(at(root, PATHS.bin), "// cross-stack-standard v0.0.0\nexport {};\n");
    assert.deepEqual(problems(root), [
      `${PATHS.bin}:1 needs exactly one "// <cross-stack-standard:generated>" … "// </cross-stack-standard:generated>" block`,
    ]);
  });

  test("a broken protected-paths pattern", (t) => {
    const root = scratchRepo(t);
    const data = readJson(at(root, "schemas/protected-paths.json"));
    data.commands[0].pattern = "([";
    write(at(root, "schemas/protected-paths.json"), data);
    const [problem] = problems(root);
    assert.match(problem, /^schemas\/protected-paths\.json:\d+ invalid regular expression: /);
  });

  test(
    "a symbolic link in the templates",
    { skip: process.platform === "win32" && "needs symlink rights" },
    (t) => {
      const root = scratchRepo(t);
      fs.symlinkSync("../shared", at(root, `${TEMPLATES}/web`));
      assert.deepEqual(problems(root), [`${TEMPLATES}/web:1 symbolic links are not allowed here`]);
    },
  );

  test(
    "a symbolic link in the data directory",
    { skip: process.platform === "win32" && "needs symlink rights" },
    (t) => {
      const root = scratchRepo(t);
      buildPluginData({ root, vendored: [] });
      fs.symlinkSync("version.json", at(root, `${DATA}/alias.json`));
      const result = buildPluginData({ root, check: true, vendored: [] });
      assert.equal(result.ok, false);
      assert.deepEqual(findingKeys(result), [`source-invalid ${DATA}/alias.json`]);
    },
  );
});

describe("vendoring", () => {
  const demoPackage = (root) => {
    write(at(root, "packages/demo/package.json"), {
      name: "@cross-stack-standard/demo",
      version: "0.0.0",
      files: ["lib"],
    });
    write(at(root, "packages/demo/README.md"), "# demo\n");
    write(at(root, "packages/demo/LICENSE"), "MIT\n");
    write(at(root, "packages/demo/lib/index.js"), "export const a = 1;\n");
    write(at(root, "packages/demo/lib/rules/b.js"), "export const b = 2;\n");
    write(at(root, "packages/demo/lib/node_modules/dep/index.js"), "nested dependency\n");
    write(at(root, "packages/demo/test/index.test.js"), "not shipped\n");
    write(at(root, "packages/demo/node_modules/dep/index.js"), "not shipped\n");
  };
  const demo = [{ source: "packages/demo", targets: ["web/vendor/demo", "mobile/vendor/demo"] }];
  const vendored = (root, track) =>
    fs
      .readdirSync(at(root, `${TEMPLATES}/${track}/vendor/demo`), {
        recursive: true,
        withFileTypes: true,
      })
      .filter((entry) => entry.isFile())
      .map((entry) =>
        path
          .relative(
            at(root, `${TEMPLATES}/${track}/vendor/demo`),
            path.join(entry.parentPath, entry.name),
          )
          .split(path.sep)
          .join("/"),
      )
      .sort();

  test("copies package.json, the files list and the readme and licence to every target", (t) => {
    const root = scratchRepo(t);
    demoPackage(root);
    const result = buildPluginData({ root, vendored: demo });
    assert.equal(result.ok, true, JSON.stringify(result.findings));
    const expected = ["LICENSE", "README.md", "lib/index.js", "lib/rules/b.js", "package.json"];
    assert.deepEqual(vendored(root, "web"), expected);
    assert.deepEqual(vendored(root, "mobile"), expected);
    const hashes = readJson(at(root, `${DATA}/template-hashes/${VERSION}.json`)).files;
    assert.ok("web/vendor/demo/lib/rules/b.js" in hashes);
    assert.equal(buildPluginData({ root, check: true, vendored: demo }).ok, true);
  });

  test("an explicit include list replaces the package.json files list", (t) => {
    const root = scratchRepo(t);
    demoPackage(root);
    const result = buildPluginData({
      root,
      vendored: [
        {
          source: "packages/demo",
          targets: ["laravel/vendor/demo"],
          include: ["package.json", "lib/rules"],
        },
      ],
    });
    assert.equal(result.ok, true, JSON.stringify(result.findings));
    assert.deepEqual(vendored(root, "laravel"), ["lib/rules/b.js", "package.json"]);
  });

  test("detects edited, extra and orphaned vendored files, and the write fixes them", (t) => {
    const root = scratchRepo(t);
    demoPackage(root);
    buildPluginData({ root, vendored: demo });
    write(at(root, `${TEMPLATES}/web/vendor/demo/lib/index.js`), "export const a = 2;\n");
    write(at(root, `${TEMPLATES}/web/vendor/demo/lib/extra/stray.js`), "stray\n");
    write(at(root, `${TEMPLATES}/shared/vendor/old/index.js`), "orphan\n");
    const check = buildPluginData({ root, check: true, vendored: demo });
    assert.deepEqual(findingKeys(check), [
      `data-drift ${TEMPLATES}/web/vendor/demo/lib/index.js`,
      `data-drift ${TEMPLATES}/shared/vendor/old/index.js`,
      `data-drift ${TEMPLATES}/web/vendor/demo/lib/extra/stray.js`,
    ]);
    const write1 = buildPluginData({ root, vendored: demo });
    assert.deepEqual(write1.removed, [
      `${TEMPLATES}/shared/vendor/old/index.js`,
      `${TEMPLATES}/web/vendor/demo/lib/extra/stray.js`,
    ]);
    assert.equal(
      fs.existsSync(at(root, `${TEMPLATES}/web/vendor/demo/lib/extra`)),
      false,
      "empty folders go too",
    );
    assert.equal(fs.existsSync(at(root, `${TEMPLATES}/shared/vendor`)), false);
    assert.equal(buildPluginData({ root, check: true, vendored: demo }).ok, true);
  });

  test("dropping a package from the list removes its vendored copies", (t) => {
    const root = scratchRepo(t);
    demoPackage(root);
    buildPluginData({ root, vendored: demo });
    const result = buildPluginData({ root, vendored: [] });
    assert.equal(result.removed.length, 10);
    assert.equal(fs.existsSync(at(root, `${TEMPLATES}/web/vendor`)), false);
  });

  test("rejects unsafe or incomplete package entries", (t) => {
    const root = scratchRepo(t);
    demoPackage(root);
    write(at(root, "packages/bare/index.php"), "<?php\n");
    const cases = [
      [{ source: "../outside", targets: ["web/vendor/x"] }, /must be a directory under packages\//],
      [{ source: "packages/demo", targets: [] }, /at least one target/],
      [
        { source: "packages/demo", targets: ["web/lib/demo"] },
        /must look like <track>\/vendor\/<name>/,
      ],
      [{ source: "packages/demo", targets: ["web/vendor/demo", "web/vendor/demo"] }, /used twice/],
      [
        { source: "packages/demo", targets: ["web/vendor/demo"], include: ["lib/*.js"] },
        /plain relative path/,
      ],
      [
        { source: "packages/demo", targets: ["web/vendor/demo"], include: ["missing"] },
        /not found/,
      ],
      [{ source: "packages/bare", targets: ["laravel/vendor/bare"] }, /has no package\.json/],
    ];
    for (const [entry, expected] of cases) {
      const result = buildPluginData({ root, vendored: [entry] });
      assert.equal(result.ok, false, JSON.stringify(entry));
      assert.match(result.findings[0].message, expected, JSON.stringify(entry));
    }
  });
});

describe("formatJson", () => {
  test("keeps short primitive arrays on one line and expands objects", () => {
    assert.equal(
      formatJson({ a: [1, "x", null, true], b: {}, c: [], d: { e: [{ f: 1 }] } }),
      '{\n  "a": [1, "x", null, true],\n  "b": {},\n  "c": [],\n  "d": {\n    "e": [\n      {\n        "f": 1\n      }\n    ]\n  }\n}\n',
    );
  });

  test("breaks a primitive array that would pass the print width", () => {
    const long = Array.from({ length: 12 }, (_, i) => `item-${i}`);
    const text = formatJson({ list: long });
    assert.ok(text.split("\n").every((line) => line.length <= 100));
    assert.match(text, /"list": \[\n {4}"item-0",\n/);
    assert.equal(formatJson({ list: ["a"] }, 12), '{\n  "list": [\n    "a"\n  ]\n}\n');
    assert.equal(formatJson({ list: ["a"] }, 15), '{\n  "list": ["a"]\n}\n');
  });

  const prettier = optionalDevDependency("prettier");
  test(
    "matches Prettier on the generated files",
    { skip: prettier ? false : "prettier is not installed (run npm ci)" },
    async (t) => {
      const root = scratchRepo(t);
      buildPluginData({ root, vendored: [] });
      for (const name of ["rules.json", "version.json", `template-hashes/${VERSION}.json`]) {
        const text = read(root, `${DATA}/${name}`);
        assert.equal(await prettier.format(text, { parser: "json", printWidth: 100 }), text, name);
      }
    },
  );
});

describe("helpers", () => {
  test("normalizeEol converts CRLF in text and leaves binary content alone", () => {
    assert.equal(normalizeEol(Buffer.from("a\r\nb\r\n")).toString(), "a\nb\n");
    const binary = Buffer.from([0, 13, 10, 1]);
    assert.equal(normalizeEol(binary), binary);
  });

  test("templateHash is the SHA-256 of the LF form", () => {
    const expected = crypto.createHash("sha256").update("x\n").digest("hex");
    assert.equal(templateHash(Buffer.from("x\r\n")), expected);
    assert.equal(templateHash(Buffer.from("x\n")), expected);
  });
});

describe("CLI", () => {
  test("--help prints usage and exits 0", () => {
    const result = runNode(BUILD_SCRIPT, ["--help"]);
    assert.equal(result.status, 0);
    assert.match(result.stdout, /^Usage: node scripts\/build-plugin-data\.mjs/);
  });

  test("an unknown option is a usage error (exit 2)", () => {
    const result = runNode(BUILD_SCRIPT, ["--bogus"]);
    assert.equal(result.status, 2);
    assert.match(result.stderr, /Unknown option '--bogus'/);
  });

  test("a missing --root is a usage error (exit 2)", (t) => {
    const result = runNode(BUILD_SCRIPT, ["--root", path.join(scratchRepo(t), "nope")]);
    assert.equal(result.status, 2);
    assert.match(result.stderr, /is not a directory/);
  });

  test("writes, then --check exits 0; drift exits 1 with one finding per line", (t) => {
    const root = scratchRepo(t);
    const first = runNode(BUILD_SCRIPT, ["--root", root]);
    assert.equal(first.status, 0, first.stderr);
    assert.match(first.stdout, /^wrote plugins\/cross-stack-standard\/data\/rules\.json$/m);
    assert.match(first.stdout, /build-plugin-data: wrote 9, removed 0, unchanged 0\n$/);

    const clean = runNode(BUILD_SCRIPT, ["--root", root, "--check"]);
    assert.equal(clean.status, 0);
    assert.equal(clean.stdout, "build-plugin-data --check: up to date (9 generated files)\n");

    write(at(root, `${DATA}/rules.json`), "{}\n");
    const drift = runNode(BUILD_SCRIPT, ["--root", root, "--check"]);
    assert.equal(drift.status, 1);
    assert.equal(
      drift.stdout,
      `data-drift ${DATA}/rules.json:1 out of date; run node scripts/build-plugin-data.mjs\n` +
        "build-plugin-data --check: 1 file(s) out of date\n",
    );
  });

  test("--json reports findings and exits 1 on invalid sources", (t) => {
    const root = scratchRepo(t);
    write(at(root, "VERSION"), "next\n");
    const result = runNode(BUILD_SCRIPT, ["--root", root, "--json"]);
    assert.equal(result.status, 1);
    const report = JSON.parse(result.stdout);
    assert.equal(report.ok, false);
    assert.deepEqual(report.findings, [
      { id: "source-invalid", path: "VERSION", line: 1, message: '"next" is not a SemVer version' },
    ]);
  });
});
