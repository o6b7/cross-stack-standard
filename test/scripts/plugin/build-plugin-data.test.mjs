describe("determinism", () => {
  test("a second run changes nothing", (t) => {
    const root = scratchRepo(t);
    buildPluginData({ root, vendored: [] });
    const before = snapshot(root);
    const second = buildPluginData({ root, vendored: [] });
    assert.deepEqual(second.written, []);
    assert.deepEqual(second.removed, []);
    assert.deepEqual(snapshot(root), before);
  });

  test("the same sources give byte-identical output, whatever the registry order", (t) => {
    const first = scratchRepo(t);
    const second = scratchRepo(t, { rules: sampleRules().reverse() });
    buildPluginData({ root: first, vendored: [] });
    buildPluginData({ root: second, vendored: [] });
    assert.deepEqual(snapshot(first), snapshot(second));
  });

  test("the committed data in this repository is up to date", () => {
    const result = buildPluginData({ root: REPO_ROOT, check: true });
    assert.deepEqual(result.findings, [], "run node scripts/build-plugin-data.mjs");
  });
});

