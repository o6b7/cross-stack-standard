const DATA = PATHS.data;
const TEMPLATES = PATHS.templates;
const at = (root, relative) => path.join(root, ...relative.split("/"));
const read = (root, relative) => fs.readFileSync(at(root, relative), "utf8");
const findingKeys = (result) => result.findings.map((finding) => `${finding.id} ${finding.path}`);

/** Snapshot of every file under the plugin folder: relative path -> sha256. */
function snapshot(root) {
  const out = {};
  const walk = (dir) => {
    for (const entry of fs.readdirSync(at(root, dir), { withFileTypes: true })) {
      const child = `${dir}/${entry.name}`;
      if (entry.isDirectory()) walk(child);
      else
        out[child] = crypto
          .createHash("sha256")
          .update(fs.readFileSync(at(root, child)))
          .digest("hex");
    }
  };
  walk("plugins");
  return out;
}

