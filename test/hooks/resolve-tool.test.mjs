/**
 * Resolving project tools to `process.execPath <bin .js>` and `php <script>`, never through
 * `.cmd`/`.bat` shims or npx, and npm/Composer themselves.
 */

import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { describe, test } from "node:test";

import { importPlugin, makeProject, tempDir, writeFile } from "./helpers/project.mjs";

const {
  binEntry,
  isJavaScriptFile,
  isPhpScript,
  isRefusedCommand,
  resolveComposer,
  resolveNodeBin,
  resolveNpmCli,
  resolveVendorBin,
} = await importPlugin("scripts/lib/resolve-tool.mjs");
const { runTool, toolEnv } = await importPlugin("scripts/lib/spawn.mjs");

const PHP_PROXY = "#!/usr/bin/env php\n<?php\n\n/** Proxy PHP file generated by Composer */\n";

describe("binEntry", () => {
  test("string and object forms", () => {
    assert.equal(binEntry("bin/cli.js", "tool"), "bin/cli.js");
    assert.equal(binEntry("bin/cli.js", "@scope/tool", "tool"), "bin/cli.js");
    assert.equal(binEntry("bin/cli.js", "tool", "other"), null);
    assert.equal(binEntry({ tool: "a.js", helper: "b.js" }, "tool"), "a.js");
    assert.equal(binEntry({ tool: "a.js", helper: "b.js" }, "tool", "helper"), "b.js");
    assert.equal(binEntry({ only: "c.js" }, "@scope/pkg"), "c.js");
    assert.equal(binEntry({ one: "a.js", two: "b.js" }, "pkg"), null);
    assert.equal(binEntry(undefined, "pkg"), null);
    assert.equal(binEntry(["a.js"], "pkg"), null);
  });
});

describe("resolveNodeBin", () => {
  test("resolves the bin's JavaScript file and runs it with process.execPath", async (t) => {
    const project = makeProject(t, {
      "node_modules/eslint/package.json": { name: "eslint", bin: { eslint: "./bin/eslint.js" } },
      "node_modules/eslint/bin/eslint.js":
        'console.log("eslint " + process.argv.slice(2).join(" "));\n',
      "node_modules/.bin/eslint.cmd": "@ECHO off\r\n",
    });
    const tool = resolveNodeBin({ pkg: "eslint", from: project.root });
    assert.equal(tool.command, process.execPath);
    assert.deepEqual(tool.args, [project.path("node_modules/eslint/bin/eslint.js")]);
    const result = await runTool({
      command: tool.command,
      args: [...tool.args, "--format", "json"],
      cwd: project.root,
      env: toolEnv(),
    });
    assert.equal(result.stdout, "eslint --format json\n");
  });

  test("a scoped package, an explicit bin name and an extensionless node script", (t) => {
    const project = makeProject(t, {
      "node_modules/@scope/tool/package.json": {
        name: "@scope/tool",
        bin: { tool: "cli", "tool-extra": "extra.cjs" },
      },
      "node_modules/@scope/tool/cli": "#!/usr/bin/env node\nconsole.log(1);\n",
      "node_modules/@scope/tool/extra.cjs": "module.exports = 1;\n",
    });
    assert.equal(
      resolveNodeBin({ pkg: "@scope/tool", from: project.root }).file,
      project.path("node_modules/@scope/tool/cli"),
    );
    assert.equal(
      resolveNodeBin({ pkg: "@scope/tool", bin: "tool-extra", from: project.root }).file,
      project.path("node_modules/@scope/tool/extra.cjs"),
    );
  });

  test("not installed, no bin, a non-JavaScript bin or a bin outside the package: null", (t) => {
    const project = makeProject(t, {
      "node_modules/nobin/package.json": { name: "nobin" },
      "node_modules/native/package.json": { name: "native", bin: "bin/native" },
      "node_modules/native/bin/native": "\u007fELF binary",
      "node_modules/escape/package.json": { name: "escape", bin: "../../evil.js" },
      "evil.js": "console.log('escaped');\n",
      "node_modules/broken/package.json": "{ not json",
    });
    for (const pkg of ["missing", "nobin", "native", "escape", "broken"]) {
      assert.equal(resolveNodeBin({ pkg, from: project.root }), null, pkg);
    }
  });

  test("a hoisted workspace dependency is found up to the stop directory, not beyond", (t) => {
    const project = makeProject(t, {
      "node_modules/prettier/package.json": { name: "prettier", bin: "bin/prettier.cjs" },
      "node_modules/prettier/bin/prettier.cjs": "console.log(1);\n",
      "apps/web/package.json": { name: "web" },
    });
    const from = project.path("apps/web");
    assert.equal(resolveNodeBin({ pkg: "prettier", from }), null, "only from by default");
    assert.equal(
      resolveNodeBin({ pkg: "prettier", from, stopAt: project.root }).file,
      project.path("node_modules/prettier/bin/prettier.cjs"),
    );
    const outside = makeProject(t);
    assert.equal(
      resolveNodeBin({ pkg: "prettier", from, stopAt: outside.root }),
      null,
      "a stop directory that is not a parent searches only the start directory",
    );
  });

  test("the nearest installation wins", (t) => {
    const project = makeProject(t, {
      "node_modules/tool/package.json": { name: "tool", bin: "root.js" },
      "node_modules/tool/root.js": "",
      "apps/web/node_modules/tool/package.json": { name: "tool", bin: "near.js" },
      "apps/web/node_modules/tool/near.js": "",
    });
    const tool = resolveNodeBin({
      pkg: "tool",
      from: project.path("apps/web"),
      stopAt: project.root,
    });
    assert.equal(tool.file, project.path("apps/web/node_modules/tool/near.js"));
  });

  test("paths with spaces resolve and run", async (t) => {
    const project = makeProject(
      t,
      {
        "node_modules/spaced/package.json": { name: "spaced", bin: "bin/run it.js" },
        "node_modules/spaced/bin/run it.js": 'console.log("ran");\n',
      },
      { name: "my project" },
    );
    const tool = resolveNodeBin({ pkg: "spaced", from: project.root });
    const result = await runTool({ command: tool.command, args: tool.args, cwd: project.root });
    assert.equal(result.stdout, "ran\n");
  });
});

describe("resolveVendorBin", () => {
  test("a Composer PHP proxy runs with php", (t) => {
    const project = makeProject(t, {
      "vendor/bin/pint": PHP_PROXY,
      "vendor/bin/pint.bat": "@ECHO OFF\r\n",
    });
    assert.deepEqual(resolveVendorBin({ name: "pint", from: project.root }), {
      command: "php",
      args: [project.path("vendor/bin/pint")],
      file: project.path("vendor/bin/pint"),
    });
  });

  test("a shell proxy or a missing tool is not used", (t) => {
    const project = makeProject(t, { "vendor/bin/tool": '#!/bin/sh\nexec php "$@"\n' });
    assert.equal(resolveVendorBin({ name: "tool", from: project.root }), null);
    assert.equal(resolveVendorBin({ name: "phpstan", from: project.root }), null);
  });

  test("searches parents up to the stop directory", (t) => {
    const project = makeProject(t, { "vendor/bin/phpstan": PHP_PROXY });
    project.mkdir("api/app");
    assert.equal(
      resolveVendorBin({ name: "phpstan", from: project.path("api/app"), stopAt: project.root })
        .file,
      project.path("vendor/bin/phpstan"),
    );
  });
});

describe("resolveNpmCli", () => {
  test("the Windows layout: npm next to node.exe", (t) => {
    const prefix = tempDir(t);
    writeFile(path.join(prefix, "node.exe"), "");
    writeFile(path.join(prefix, "node_modules/npm/bin/npm-cli.js"), "");
    const execPath = path.join(prefix, "node.exe");
    const npm = resolveNpmCli({ env: {}, execPath });
    assert.equal(npm.command, execPath);
    assert.deepEqual(npm.args, [path.join(prefix, "node_modules/npm/bin/npm-cli.js")]);
  });

  test("the Unix layout: <prefix>/lib/node_modules/npm", (t) => {
    const prefix = tempDir(t);
    writeFile(path.join(prefix, "bin/node"), "");
    writeFile(path.join(prefix, "lib/node_modules/npm/bin/npm-cli.js"), "");
    const npm = resolveNpmCli({ env: {}, execPath: path.join(prefix, "bin/node") });
    assert.equal(npm.file, path.join(prefix, "lib/node_modules/npm/bin/npm-cli.js"));
  });

  test("npm_execpath wins when it names npm-cli.js; another package manager's is ignored", (t) => {
    const dir = tempDir(t);
    const cli = path.join(dir, "custom/npm-cli.js");
    writeFile(cli, "");
    writeFile(path.join(dir, "pnpm.cjs"), "");
    const execPath = path.join(dir, "bin/node");
    assert.equal(resolveNpmCli({ env: { npm_execpath: cli }, execPath }).file, cli);
    assert.equal(
      resolveNpmCli({ env: { npm_execpath: path.join(dir, "pnpm.cjs") }, execPath }),
      null,
    );
  });

  test("the running Node.js's own npm starts without a shell", async (t) => {
    const npm = resolveNpmCli({ env: {} });
    if (npm === null) {
      t.skip("this Node.js installation has no bundled npm");
      return;
    }
    const result = await runTool({
      command: npm.command,
      args: [...npm.args, "--version"],
      cwd: tempDir(t),
      env: toolEnv(process.env, { npm_config_update_notifier: "false" }),
      timeoutMs: 30_000,
    });
    assert.equal(result.exitCode, 0, result.output);
    assert.match(result.stdout.trim(), /^\d+\.\d+\.\d+/);
  });
});

describe("resolveComposer", () => {
  test("composer.phar on PATH (the Windows installer keeps composer.bat next to it)", (t) => {
    const dir = tempDir(t);
    writeFile(path.join(dir, "composer.bat"), '@php "%~dp0composer.phar" %*\r\n');
    writeFile(path.join(dir, "composer.phar"), PHP_PROXY);
    const composer = resolveComposer({ env: { Path: ["/nowhere", dir].join(path.delimiter) } });
    assert.deepEqual(composer, {
      command: "php",
      args: [path.join(dir, "composer.phar")],
      file: path.join(dir, "composer.phar"),
    });
  });

  test("a `composer` file that is a PHP script; a shell wrapper is skipped", (t) => {
    const wrapper = tempDir(t);
    const real = tempDir(t);
    writeFile(path.join(wrapper, "composer"), '#!/bin/sh\nexec php composer.phar "$@"\n');
    writeFile(path.join(real, "composer"), PHP_PROXY);
    const composer = resolveComposer({ env: { PATH: [wrapper, real].join(path.delimiter) } });
    assert.equal(composer.file, path.join(real, "composer"));
    assert.equal(resolveComposer({ env: { PATH: wrapper } }), null);
    assert.equal(resolveComposer({ env: {} }), null);
  });
});

describe("file checks", () => {
  test("isJavaScriptFile and isPhpScript", (t) => {
    const dir = tempDir(t);
    const files = {
      "a.js": "",
      "b.mjs": "",
      "c.CJS": "",
      shebang: "#!/usr/bin/env node\n",
      "shebang-flags": "#!/usr/bin/env -S node --no-warnings\n",
      sh: "#!/bin/sh\n",
      php: "<?php\n",
      "php-crlf": "#!/usr/bin/env php\r\n<?php\r\n",
    };
    for (const [name, content] of Object.entries(files)) writeFile(path.join(dir, name), content);
    const js = Object.keys(files).filter((name) => isJavaScriptFile(path.join(dir, name)));
    const php = Object.keys(files).filter((name) => isPhpScript(path.join(dir, name)));
    assert.deepEqual(js, ["a.js", "b.mjs", "c.CJS", "shebang", "shebang-flags"]);
    assert.deepEqual(php, ["php", "php-crlf"]);
    assert.equal(isJavaScriptFile(dir), false, "a directory is not a script");
    assert.equal(fs.existsSync(path.join(dir, "missing.js")), false);
    assert.equal(isJavaScriptFile(path.join(dir, "missing.js")), false);
  });

  test("isRefusedCommand", () => {
    for (const command of [
      "npx",
      "npx.exe",
      "/usr/local/bin/npx",
      "C:\\npm\\npx.cmd",
      "a.bat",
      "b.PS1",
    ]) {
      assert.equal(isRefusedCommand(command), true, command);
    }
    for (const command of [process.execPath, "php", "node", "/opt/npx-helper/tool.js"]) {
      assert.equal(isRefusedCommand(command), false, command);
    }
  });
});
